"""Dinosaurs world: cute cartoon dinosaurs (and flying / swimming reptiles) as hand-made SVG.  Writes tests/dinos.js.

All the pictures live in dinos_more_*.py (one add_more(K) per file); dinos_kit.py has the shared
style helpers.  Letters with no well-known dinosaur (F, J, W, X, Y, Z) are simply left out, and
the game skips them in this world.

Run:  python tests/dinos_make.py   then   python tests/pack_sheet.py tests/dinos.js dinos_sheet.png
"""
import os
from svgkit import Pack, add_extensions

K = Pack()
add_extensions(K, "dinos")
K.write(os.path.join(os.path.dirname(os.path.abspath(__file__)), "dinos.js"),
        "DINO_ITEMS", "DINOS", "Dinosaurs world: cartoon dinosaurs, hand-made SVG (viewBox 0 0 100 100). Letters without a dinosaur are left out. Generated by dinos_make.py.",
        allow_missing=True)
