def _edge(p, q, kind, r=6.0, half=3.6):
    """Jigsaw edge from p to q (clockwise piece). kind 0 flat, 1 knob out, -1 hole in."""
    if kind == 0:
        return f"L{q[0]:.1f} {q[1]:.1f}"
    mx, my = (p[0] + q[0]) / 2, (p[1] + q[1]) / 2
    ln = math.hypot(q[0] - p[0], q[1] - p[1])
    ux, uy = (q[0] - p[0]) / ln, (q[1] - p[1]) / ln
    a = (mx - ux * half, my - uy * half); b = (mx + ux * half, my + uy * half)
    sweep = 1 if kind == 1 else 0
    return (f"L{a[0]:.1f} {a[1]:.1f}A{r} {r} 0 1 {sweep} {b[0]:.1f} {b[1]:.1f}"
            f"L{q[0]:.1f} {q[1]:.1f}")


def piece(x, y, s, top, right, bottom, left):
    c = [(x, y), (x + s, y), (x + s, y + s), (x, y + s)]
    d = f"M{x:.1f} {y:.1f}"
    for i, k in enumerate((top, right, bottom, left)):
        d += _edge(c[i], c[(i + 1) % 4], k)
    return d + "Z"


